# ---------- schema (the subset of JSON Schema that tuning/schema.json uses; no third-party validator) ----------

def validate(value, schema, root=None, path="$"):
    root = root or schema
    if "$ref" in schema:
        node = root
        for part in schema["$ref"].lstrip("#/").split("/"):
            node = node[part]
        return validate(value, node, root, path)
    if "oneOf" in schema:
        ok = [s for s in schema["oneOf"] if not validate(value, s, root, path)]
        return [] if len(ok) == 1 else [f"{path}: must match exactly one alternative"]
    errors = []
    types = {"object": dict, "array": list, "string": str, "integer": int}
    t = schema.get("type")
    if t and (not isinstance(value, types[t]) or (t == "integer" and isinstance(value, bool))):
        return [f"{path}: expected {t}, got {type(value).__name__}"]
    if "enum" in schema and value not in schema["enum"]:
        errors.append(f"{path}: {value!r} not in {schema['enum']}")
    if "pattern" in schema and not re.search(schema["pattern"], value):
        errors.append(f"{path}: {value!r} does not match {schema['pattern']}")
    if "minimum" in schema and value < schema["minimum"]:
        errors.append(f"{path}: {value} < {schema['minimum']}")
    if "maximum" in schema and value > schema["maximum"]:
        errors.append(f"{path}: {value} > {schema['maximum']}")
    if t == "array":
        if len(value) < schema.get("minItems", 0):
            errors.append(f"{path}: needs at least {schema['minItems']} item(s)")
        for i, item in enumerate(value):
            errors += validate(item, schema.get("items", {}), root, f"{path}[{i}]")
    if t == "object":
        props = schema.get("properties", {})
        for key in schema.get("required", []):
            if key not in value:
                errors.append(f"{path}: missing required '{key}'")
        if len(value) < schema.get("minProperties", 0):
            errors.append(f"{path}: needs at least {schema['minProperties']} field(s)")
        for key, v in value.items():
            if key in props:
                errors += validate(v, props[key], root, f"{path}.{key}")
            elif schema.get("additionalProperties") is False:
                errors.append(f"{path}: unknown field '{key}'")
    return errors


def as_list(v):
    return v if isinstance(v, list) else [v]


# ---------- ladder model: how Wazuh selects among siblings ----------

def engine_key(level, order):
    """Wazuh 4.x evaluates sibling rules level 0 first, then by descending level; file order breaks ties.
    (Observed on 4.14.9 - a lower placed before a raise does not win.)"""
    return (0 if level == 0 else 1, -level, order)


def ladder():
    """Rule id -> {level, parent, fields, order} for the hand-written ladder, plus stock 86601."""
    root = ET.fromstring(f"<root>{LADDER.read_text()}</root>")
    rules = {"86601": {"level": 3, "parent": None, "fields": {}, "order": -1}}
    for n, r in enumerate(root.iter("rule")):
        rules[r.get("id")] = {"level": int(r.get("level")), "parent": r.findtext("if_sid"),
                              "fields": {f.get("name"): f.text for f in r.findall("field")}, "order": n}
    return rules


def children(rules, parent):
    kids = [rid for rid, r in rules.items() if r["parent"] == str(parent)]
    return sorted(kids, key=lambda rid: engine_key(rules[rid]["level"], rules[rid]["order"]))


def ladder_select(rules, metadata):
    """The ladder rule an alert with this metadata lands on (before any tuning rule)."""
    node = "86601"
    while True:
        for kid in children(rules, node):
            want = {k.split(".", 2)[2]: v for k, v in rules[kid]["fields"].items() if k.startswith("alert.metadata.")}
            if all(metadata.get(k) == v for k, v in want.items()):
                node = kid
                break
        else:
            return node


# ---------- semantic checks ----------

def canonical_ip(value):
    try:
        return str(ipaddress.ip_address(value)) == value
    except ValueError:
        return False


def routes_overlap(a, b):
    """Could one event match both routes? A field missing on one side matches anything."""
    return all(set(map(str, as_list(a[k]))) & set(map(str, as_list(b[k]))) for k, _ in ROUTE_FIELDS
               if k in a and k in b)


def check_semantics(intent, alert_level, rules=None):
    """Rules the schema cannot express. Each one encodes a lesson from docs/PLAYBOOK.md or a review finding."""
    rules = rules or ladder()
    errors, action, routes = [], intent["action"], intent.get("routes", [])
    for route in routes:
        for key in ("src", "dst"):
            ips = as_list(route.get(key, []))
            if any(not canonical_ip(ip) for ip in ips):
                errors.append(f"{key} {ips}: addresses must be valid and canonical (10.10.20.15, not 010.010.020.015)")
            if len(ips) > MAX_ADDRESSES:
                errors.append(f"{key}: {len(ips)} addresses in one route - a context that wide is a different decision")
    if action in SIEM_ACTIONS:
        for key in ("routes", "level", "description", "wazuh", "metadata"):
            if key not in intent:
                errors.append(f"action {action} needs '{key}'")
        if errors:
            return errors
        parent, level = str(intent["wazuh"]["parent"]), intent["level"]
        leaves = {rid for rid in rules if rid != "86601" and not children(rules, rid)}
        if parent not in leaves:
            errors.append(f"wazuh.parent {parent} must be a leaf of the ladder {sorted(leaves)} - under a non-leaf "
                          "parent a ladder sibling can take the event and the tuning rule never fires")
        landed = ladder_select(rules, intent["metadata"])
        if landed != parent:
            errors.append(f"metadata {intent['metadata']} lands on ladder rule {landed}, not on wazuh.parent {parent}")
        if len(intent["wazuh"]["rule_ids"]) != len(routes):
            errors.append("wazuh.rule_ids needs one ID per route (a union of routes is not one rule)")
        if action == "lower" and not 1 <= level < alert_level:
            errors.append(f"lower needs 1 <= level < {alert_level}: level 0 is evaluated before every sibling "
                          "and would win over any raise")
        if action in ("enrich", "raise") and level < alert_level:
            errors.append(f"{action} must stay visible: level >= {alert_level}")
        if action == "lower" and any(not {"dst", "dst_port"} <= set(r) for r in routes):
            errors.append("lower needs dst and dst_port in every route - a host or a port alone hides far more "
                          "than the verified context")
        if "rate_limit" in intent:
            if action != "enrich":
                errors.append("rate_limit only for enrich: `ignore` is global for the rule and would hide repeats "
                              "the parent alerts on")
            if any(len(as_list(r.get(k, []))) > 1 for r in routes for k in ("src", "dst")):
                errors.append("rate_limit needs one address per route field: all addresses of a route share one "
                              "ignore window")
        if re.search(r"[&<>]", intent["description"]):
            errors.append("description must not contain & < > - Wazuh would show the escaped entities literally")
        if re.search(r"\b\d{1,3}(\.\d{1,3}){3}\b", intent["description"]):
            errors.append("description has a literal IP; use $(src_ip)/$(dest_ip)")
    if action == "suppress":
        if not routes:
            errors.append("suppress needs routes; a SID off everywhere is 'disable'")
        for r in routes:
            if set(r) - {"src", "dst"} or len(r) != 1:
                errors.append("Suricata suppress tracks one address side only (by_src or by_dst) and cannot pin "
                              "ports or protocol - use action 'lower' in the SIEM for an exact context")
    if action == "disable" and routes:
        errors.append("disable is global; for a context use 'suppress' or 'lower'")
    if action in ("suppress", "disable") and ({"wazuh", "rate_limit", "level", "metadata"} & set(intent)):
        errors.append(f"{action} is a Suricata-side action; wazuh/rate_limit/level/metadata do not apply")
    control = re.sub(r"[\W_]+", " ", intent["compensating_control"]).strip().lower()
    unnamed = control in ("", "none", "n a", "na", "nothing", "tbd") or len(control) < 4
    if action in ("suppress", "disable") and unnamed:
        errors.append(f"{action} removes the event even from archives - name the compensating control")
    return errors


def registry():
    """wazuh/README.md -> (ids in the registry table, held ids, retired ids)."""
    text = REGISTRY.read_text() if REGISTRY.exists() else ""
    section = text.split("## Registry", 1)[-1].split("\n## ", 1)[0]
    table = {int(m) for m in re.findall(r"^\| (\d+) \|", section, re.M)}

    def ids(label):
        line = next((row for row in section.splitlines() if row.startswith(label)), "")
        out = set()
        for a, b in re.findall(r"(\d{5,})(?:-(\d{5,}))?", line):
            out |= set(range(int(a), int(b or a) + 1))
        return out
    return table, ids("Held:"), ids("Retired:")


def check_ids(intents, id_range, rules):
    """Rule IDs: inside the range, not ladder, held or retired, unique, and a row in the registry table."""
    errors, seen = [], {}
    table, held, retired = registry()
    lo, hi = id_range
    for intent in intents:
        for rid in intent.get("wazuh", {}).get("rule_ids", []):
            where = f"{intent['id']}: rule id {rid}"
            if not lo <= rid <= hi:
                errors.append(f"{where} outside RULE_ID_RANGE {lo}-{hi}")
            if str(rid) in rules or rid in held:
                errors.append(f"{where} is a ladder or reserved ID")
            if rid in retired:
                errors.append(f"{where} is retired - never reuse a retired ID")
            if rid in seen:
                errors.append(f"{where} already used by {seen[rid]}")
            if rid not in table:
                errors.append(f"{where} is not in the registry wazuh/README.md")
            seen[rid] = intent["id"]
    return errors


def check_overlaps(intents):
    """Two tuning rules that can match the same event: Wazuh picks by level, not by file order, so the
    outcome would depend on levels nobody reviewed together. Refuse instead."""
    errors, rows = [], wazuh_rules(intents)
    for (i1, r1, id1), (i2, r2, id2) in itertools.combinations(rows, 2):
        if i1["wazuh"]["parent"] == i2["wazuh"]["parent"] and set(i1["sids"]) & set(i2["sids"]) and \
                routes_overlap(r1, r2):
            errors.append(f"rules {id1} ({i1['id']}) and {id2} ({i2['id']}) overlap - merge the decisions or make "
                          "the routes disjoint")
    return errors


def check_metadata(intents):
    """A SID has one metadata: two intents declaring different values cannot both be right (one is dead)."""
    errors, seen = [], {}
    for intent in intents:
        for sid in intent["sids"] if "metadata" in intent else []:
            if sid in seen and seen[sid][1] != intent["metadata"]:
                errors.append(f"SID {sid}: metadata {intent['metadata']} in {intent['id']} differs from "
                              f"{seen[sid][1]} in {seen[sid][0]}")
            seen.setdefault(sid, (intent["id"], intent["metadata"]))
    return errors


def rule_metadata(paths):
    """SID -> {metadata key: value} from Suricata rule files (first value of each key)."""
    known = {}
    for path in paths:
        files = sorted(pathlib.Path(path).glob("*.rules")) if pathlib.Path(path).is_dir() else [pathlib.Path(path)]
        for f in (f for f in files if f.is_file()):
            for line in f.read_text(errors="replace").splitlines():
                sid, meta = re.search(r"\bsid:\s*(\d+)\s*;", line), re.search(r"\bmetadata:\s*([^;]*);", line)
                if sid and not line.lstrip().startswith("#"):
                    pairs = (p.strip().split(None, 1) for p in (meta.group(1).split(",") if meta else []))
                    known[int(sid.group(1))] = {p[0]: p[1].strip() for p in pairs if len(p) == 2}
    return known


def check_rule_metadata(intents, known):
    """The metadata an intent declares must be what the rule text says - otherwise the ladder sends the alert
    elsewhere and the tuning rule never fires, while the generated tests (built from the intent) still pass."""
    errors = []
    for intent in (i for i in intents if "metadata" in i):
        for sid in (s for s in intent["sids"] if s in known):
            actual = {k: known[sid].get(k) for k in intent["metadata"]}
            if actual != intent["metadata"]:
                errors.append(f"{intent['id']}: SID {sid} declares {intent['metadata']} "
                              f"but its rule text says {actual}")
    return errors


def rule_sources(cfg):
    """Rule files to check intents against: the repo's local rules and corpus stand-ins, plus an optional local
    cache of the sensor's rule lines (SURICATA_RULES_CACHE, git-ignored - rule text, not telemetry)."""
    sources = [ROOT / "suricata" / "rules", ROOT / "tests" / "corpus" / "lab-standins.rules"]
    if cfg.get("SURICATA_RULES_CACHE"):
        sources.append(pathlib.Path(cfg["SURICATA_RULES_CACHE"]).expanduser())
    return sources


def load_intents(directory=INTENTS, alert_level=None, id_range=None):
    cfg = kitconfig.load()
    alert_level = alert_level if alert_level is not None else int(cfg["WAZUH_ALERT_LEVEL"])
    id_range = id_range or tuple(int(x) for x in cfg["RULE_ID_RANGE"].split("-"))
    schema, rules = json.loads(SCHEMA.read_text()), ladder()
    intents, errors = [], []
    for path in sorted(pathlib.Path(directory).glob("*.yaml")):
        intent = yaml.safe_load(path.read_text())
        problems = validate(intent, schema)
        if not problems:
            problems = check_semantics(intent, alert_level, rules)
            if intent["id"] != path.stem:
                problems.append(f"id '{intent['id']}' must equal the file name")
        errors += [f"{path.name}: {p}" for p in problems]
        if not problems and intent["status"] == "approved":
            intents.append(intent)
    if not errors:
        errors = (check_ids(intents, id_range, rules) + check_overlaps(intents) + check_metadata(intents) +
                  check_rule_metadata(intents, rule_metadata(rule_sources(cfg))))
    if errors:
        raise IntentError("\n".join(errors))
    return intents


# ---------- wazuh4-xml ----------

def regex(values, field):
    esc = [re.escape(str(v)) if field != "proto" else str(v) for v in as_list(values)]
    return f"^{esc[0]}$" if len(esc) == 1 else "^(?:" + "|".join(esc) + ")$"


def wazuh_rules(intents):
    """[(intent, route, rule_id)] in file order."""
    return [(i, r, rid) for i in intents if i["action"] in SIEM_ACTIONS
            for r, rid in zip(i["routes"], i["wazuh"]["rule_ids"])]


def field_regex(values, field):
    """A field regex that needed XML escaping would be compared escaped and never match - refuse it."""
    rx = regex(values, field)
    if escape(rx) != rx:
        raise IntentError(f"{field}: {rx!r} needs XML escaping and could never match")
    return rx


def comment(text):
    """Text inside <!-- -->: escaped, no `--` (which would end or invalidate the comment)."""
    return re.sub(r"-{2,}", "-", escape(" ".join(str(text).split())))


def render_wazuh4(intents):
    out = [f"<!-- {HEADER} -->", '<group name="suricata,tuning,">']
    rows = wazuh_rules(intents)
    for intent, route, rid in rows:
        ignore = f' ignore="{intent["rate_limit"]["ignore_seconds"]}"' if "rate_limit" in intent else ""
        head = f"    {comment(intent['id'])} ({intent['action'].upper()}) - card: {comment(intent['card'])}"
        out += ["", "  <!--", head]
        for label, key in (("Why", "rationale"), ("Risk", "risk"), ("Compensating control", "compensating_control")):
            out.append(f"    {label}: {comment(intent[key])}")
        out += ["  -->", f'  <rule id="{int(rid)}" level="{int(intent["level"])}"{ignore}>',
                f"    <if_sid>{int(intent['wazuh']['parent'])}</if_sid>",
                f'    <field name="alert.signature_id" type="pcre2">{field_regex(intent["sids"], "sid")}</field>']
        for key, field in ROUTE_FIELDS:
            if key in route:
                out.append(f'    <field name="{field}" type="pcre2">{field_regex(route[key], key)}</field>')
        out += [f"    <description>{escape(' '.join(intent['description'].split()))}</description>",
                f"    <group>suricata,tuning,{intent['id'].replace('-', '_')},</group>", "  </rule>"]
    out.append("</group>")
    xml = "\n".join(out) + "\n"
    # Whatever the text fields contain, the file must hold exactly the rules the intents declare.
    parsed = [(r.get("id"), r.findtext("if_sid")) for r in ET.fromstring(f"<root>{xml}</root>").iter("rule")]
    declared = [(str(rid), str(i["wazuh"]["parent"])) for i, _, rid in rows]
    if parsed != declared:
        raise IntentError(f"rendered rules {parsed} differ from the declared {declared}")
    return xml


# ---------- suricata-threshold ----------

def render_suricata(intents):
    thr = [f"# {HEADER}", "# Suricata suppress drops the alert entirely - nothing reaches the SIEM or its archives."]
    dis = [f"# {HEADER}", "# suricata-update disable.conf: these signatures are off on the sensor everywhere."]
    for intent in intents:
        if intent["action"] == "suppress":
            for sid in intent["sids"]:
                for route in intent["routes"]:
                    side, ips = next(iter(route.items()))
                    track = "by_src" if side == "src" else "by_dst"
                    # comment on its own line: Suricata rejects the whole line if a comment trails it
                    thr += [f"# {intent['id']}",
                            f"suppress gen_id 1, sig_id {sid}, track {track}, ip {','.join(as_list(ips))}"]
        elif intent["action"] == "disable":
            for sid in intent["sids"]:
                dis += [f"# {intent['id']}", f"1:{sid}"]
    return {"threshold.config": "\n".join(thr) + "\n", "disable.conf": "\n".join(dis) + "\n"}


# ---------- wazuh5 (experimental) ----------
# Wazuh 5 rules are self-contained Sigma documents (no if_sid, no frequency/ignore); every match is a finding.
# Assumptions to confirm with content-manager logtest on a 5.x deployment (listed in wazuh5/GAPS.md):
WCS_FIELDS = {"src": "source.ip", "dst": "destination.ip", "src_port": "source.port", "dst_port": "destination.port",
              "proto": "network.transport"}
WCS_SID = "rule.id"           # ECS/WCS: the observer's rule (the Suricata signature) - not wazuh.rule.id
WAZUH5_PRODUCT = "suricata"   # logsource.product must be the title of the integration the rule belongs to
# 4.x level -> 5.x keyword, from the migration guide's table
LEVEL_KEYWORDS = [(0, None), (3, "informational"), (6, "low"), (9, "medium"), (13, "high"), (16, "critical")]
KEYWORD_ORDER = ["informational", "low", "medium", "high", "critical"]


def level_keyword(level):
    return next(kw for top, kw in LEVEL_KEYWORDS if level <= top)


def wcs_selection(route):
    out = {}
    for key, field in WCS_FIELDS.items():
        if key in route:
            values = [str(v).lower() if key == "proto" else v for v in as_list(route[key])]
            out[field] = values[0] if len(values) == 1 else values
    return out


def wazuh5_rule(title, level, detection, description, references, tags):
    return {"enabled": True, "status": "experimental", "level": level,
            "metadata": {"title": title, "author": "suricata-tuning-agents (generated by tools/render.py)",
                         "description": " ".join(description.split()), "references": references},
            "logsource": {"product": WAZUH5_PRODUCT, "category": "ids"},
            "detection": detection, "tags": tags}


def wazuh5_rules(intents):
    """{file name: rule dict}. Per tuned SID and ladder parent: one rule for the SID outside the tuned routes at
    the parent's level, and one rule per route at the intent's level."""
    rules, ladder_rules, by_sid = {}, ladder(), {}
    for intent, route, rid in wazuh_rules(intents):
        for sid in intent["sids"]:
            by_sid.setdefault((sid, str(intent["wazuh"]["parent"])), []).append((intent, route, rid))
    for (sid, parent), rows in sorted(by_sid.items()):
        tuned = {f"tuned_{n}": dict({WCS_SID: sid}, **wcs_selection(route)) for n, (_, route, _) in enumerate(rows, 1)}
        detection = dict({"selection": {WCS_SID: sid}}, **tuned, condition="selection and not 1 of tuned_*")
        rules[f"sid-{sid}-default.yml"] = wazuh5_rule(
            f"Suricata SID {sid} outside its tuned contexts", level_keyword(ladder_rules[parent]["level"]), detection,
            f"Replaces the 4.x ladder rule {parent} for SID {sid} except the contexts tuned by "
            + ", ".join(sorted({i["id"] for i, _, _ in rows})) + ".",
            [f"4.x ladder rule {parent}"] + sorted({f"intent {i['id']}" for i, _, _ in rows}), ["tuning", f"sid.{sid}"])
    for intent, route, rid in wazuh_rules(intents):
        detection = {"selection": dict({WCS_SID: intent["sids"][0] if len(intent["sids"]) == 1 else intent["sids"]},
                                       **wcs_selection(route)), "condition": "selection"}
        rules[f"{intent['id']}-{rid}.yml"] = wazuh5_rule(
            f"{intent['id']} ({intent['action'].upper()}, 4.x rule {rid})", level_keyword(intent["level"]), detection,
            f"{intent['description']} Why: {intent['rationale']} Risk: {intent['risk']} "
            f"Compensating control: {intent['compensating_control']}",
            [f"intent {intent['id']}", f"card {intent['card']}", f"4.x rule {rid}"], ["tuning", intent["id"]])
    return rules


def wazuh5_gaps(intents, alert_level):
    sids = sorted({sid for i, _, _ in wazuh_rules(intents) for sid in i["sids"]})
    lines = [f"# Wazuh 5 adapter - gaps and assumptions ({HEADER})", "",
             "Experimental: written against the official 4.x->5.x rules migration guide for 5.0.0-rc2. Not "
             "engine-verified - the 5.x Suricata integration ships through Wazuh CTI at runtime, and rules are "
             "evaluated by the indexer, so there is no offline logtest. Evidence: `static` + the rule model in "
             "tests/unit/test_render.py (same cases as the 4.x logtest files).", "",
             "## Assumptions to confirm with content-manager logtest", "",
             f"- Signature id in `{WCS_SID}`; addresses and ports in "
             + ", ".join(f"`{f}`" for f in WCS_FIELDS.values()) + " (`network.transport` lower-case).",
             f"- `logsource.product: {WAZUH5_PRODUCT}` is the title of the integration the rules belong to.",
             f"- Analyst-visible threshold: findings at `{level_keyword(alert_level)}` or above "
             f"(4.x level {alert_level}, mapped with the guide's table).", "",
             "## Generic severity rules must skip the tuned SIDs", "",
             "Rules no longer chain, so a generic Suricata severity rule still matches a lowered event. Add this "
             "filter to those rules; the per-SID rules in `rules/` take over:", "", "```yaml",
             "filter_tuned_sids:", f"  {WCS_SID}: [{', '.join(map(str, sids))}]",
             "# condition: <existing> and not filter_tuned_sids", "```", "", "## Not expressible in 5.0", ""]
    gaps = [i for i in intents if "rate_limit" in i]
    for i in gaps:
        lines.append(f"- `{i['id']}`: `ignore` {i['rate_limit']['ignore_seconds']} s (ENRICH rate limit) - no "
                     "correlation or suppression in the 5.0 rule format; every event becomes a finding. Option: an "
                     "Alerting monitor over the findings index.")
    if not gaps:
        lines.append("- nothing in the current intents")
    return "\n".join(lines) + "\n"


def render_wazuh5(intents, alert_level=6):
    """{relative path: text} - Sigma YAML per rule plus GAPS.md."""
    files = {f"rules/{name}": f"# {HEADER}\n" + yaml.safe_dump(rule, sort_keys=False, allow_unicode=True)
             for name, rule in wazuh5_rules(intents).items()}
    files["GAPS.md"] = wazuh5_gaps(intents, alert_level)
    return files


def sigma_match(rule, doc):
    """Evaluate the condition shapes this adapter generates (identifiers, and/or/not, `1 of x_*`, parentheses)."""
    det = rule["detection"]

    def selection(name):
        return all(str(doc.get(f)) in {str(v) for v in as_list(vals)} for f, vals in det[name].items())

    tokens = det["condition"].replace("(", " ( ").replace(")", " ) ").split()
    pos = 0

    def parse_or():
        nonlocal pos
        value = parse_and()
        while pos < len(tokens) and tokens[pos] == "or":
            pos += 1
            value = parse_and() or value
        return value

    def parse_and():
        nonlocal pos
        value = parse_not()
        while pos < len(tokens) and tokens[pos] == "and":
            pos += 1
            value = parse_not() and value
        return value

    def parse_not():
        nonlocal pos
        if tokens[pos] == "not":
            pos += 1
            return not parse_not()
        if tokens[pos] == "(":
            pos += 1
            value = parse_or()
            pos += 1
            return value
        if tokens[pos] in ("1", "all") and tokens[pos + 1] == "of":
            quant, pattern, pos = tokens[pos], tokens[pos + 2], pos + 3
            names = [n for n in det if n != "condition" and re.fullmatch(pattern.replace("*", ".*"), n)]
            return (any if quant == "1" else all)(selection(n) for n in names)
        name, pos = tokens[pos], pos + 1
        return selection(name)

    return parse_or()


def wcs_doc(sid, ctx):
    return {WCS_SID: sid, "source.ip": ctx["src"], "destination.ip": ctx["dst"], "source.port": ctx["src_port"],
            "destination.port": ctx["dst_port"], "network.transport": ctx["proto"].lower()}


# ---------- test generation ----------

def event(intent, sid, ctx):
    return {"timestamp": "2026-01-05T10:00:00.000000+0100", "flow_id": 1, "in_iface": "eth1", "event_type": "alert",
            "src_ip": ctx["src"], "src_port": ctx["src_port"], "dest_ip": ctx["dst"], "dest_port": ctx["dst_port"],
            "proto": ctx["proto"],
            "alert": {"action": "allowed", "gid": 1, "signature_id": sid, "rev": 1, "signature": intent["signature"],
                      "category": "Generated test", "severity": 2,
                      "metadata": {k: [v] for k, v in intent["metadata"].items()}}}


def route_matches(route, ctx):
    return all(ctx[k] in as_list(route[k]) for k, _ in ROUTE_FIELDS if k in route)


def expected(intents, rules, sid, ctx, metadata, fired, alert_level):
    """Model of Wazuh: the ladder picks the parent from the metadata; among the tuning children of that parent
    the engine order decides (engine_key); no match -> the parent itself."""
    parent = ladder_select(rules, metadata)
    rows = [(intent, route, rid, n) for n, (intent, route, rid) in enumerate(wazuh_rules(intents))
            if str(intent["wazuh"]["parent"]) == parent and sid in intent["sids"] and route_matches(route, ctx)]
    if rows:
        intent, _, rid, _ = min(rows, key=lambda row: engine_key(row[0]["level"], row[3]))
        level = intent["level"]
        alert = level >= alert_level and not ("rate_limit" in intent and rid in fired)
        fired.add(rid)
        return str(rid), level, alert
    level = rules[parent]["level"]
    return parent, level, level >= alert_level


def contexts(route):
    keys = [k for k, _ in ROUTE_FIELDS if k in route]
    for combo in itertools.product(*(as_list(route[k]) for k in keys)):
        yield dict(DEFAULT_EVENT, **dict(zip(keys, combo)))


def extend_ip(ip):
    """Addresses an unanchored regex for `ip` would also match: longer last octet, longer first octet."""
    a, b, c, d = ip.split(".")
    out = [f"{a}.{b}.{c}.{d}{n}" for n in "05" if int(d + n) <= 255][:1]
    out += [f"{n}{a}.{b}.{c}.{d}" for n in "12" if int(n + a) <= 255][:1]
    return out


def negatives(intent):
    """(note, sid, ctx) cases that must NOT be selected by this intent's rules."""
    cases, routes = [], intent["routes"]
    for sid in intent["sids"]:  # look-alike SIDs: an unanchored SID regex would match them
        for probe in (int(f"{sid}0"), int(f"1{sid}")):
            if probe not in intent["sids"]:
                cases.append((f"SID {probe} extends {sid} (anchoring)", probe, next(contexts(routes[0]))))
    sid = intent["sids"][0]
    for n, route in enumerate(routes, 1):
        for ctx in contexts(route):
            tag = f"route {n} {ctx['src'] if 'src' in route else ''}->{ctx['dst'] if 'dst' in route else ''}".strip()
            for key in ("src", "dst"):
                if key in route:
                    for ip in extend_ip(ctx[key]):
                        cases.append((f"{tag}: {key} {ip} extends {ctx[key]} (anchoring)", sid, dict(ctx, **{key: ip})))
            rev = dict(ctx, src=ctx["dst"], dst=ctx["src"], src_port=ctx["dst_port"], dst_port=ctx["src_port"])
            cases.append((f"{tag}: reverse direction", sid, rev))
        base = next(contexts(route))
        for nsid in intent.get("tests", {}).get("neighbour_sids", []):
            cases.append((f"route {n}: neighbour SID {nsid} untouched", nsid, base))
        if "dst_port" in route:
            cases.append((f"route {n}: other port", sid, dict(base, dst_port=max(as_list(route["dst_port"])) + 1)))
        if "src_port" in route:
            other = max(as_list(route["src_port"])) + 1
            cases.append((f"route {n}: other source port", sid, dict(base, src_port=other)))
        if "proto" in route:
            other = next(p for p in ("TCP", "UDP", "ICMP") if p not in as_list(route["proto"]))
            cases.append((f"route {n}: other protocol", sid, dict(base, proto=other)))
    for (i, a), (j, b) in itertools.permutations(enumerate(routes, 1), 2):
        for key in set(a) & set(b):
            if as_list(a[key]) != as_list(b[key]):
                crossed = dict(next(contexts(a)), **{key: as_list(b[key])[0]})
                cases.append((f"crossed: route {i} with {key} of route {j}", sid, crossed))
    return [(note, s, ctx) for note, s, ctx in cases
            if not any(route_matches(r, ctx) for r in routes) or s not in intent["sids"]]


def test_cases(intent):
    """(note, sid, ctx) for one intent: positives (and ignore-window repeats), negatives, hand-written extras."""
    cases = []
    for n, route in enumerate(intent["routes"], 1):
        for ctx in contexts(route):
            for sid in intent["sids"]:
                cases.append((f"route {n}: {intent['action']} SID {sid}", sid, ctx))
                if "rate_limit" in intent:
                    cases.append((f"route {n}: repeat inside ignore window", sid, ctx))
    cases += negatives(intent)
    for x in intent.get("tests", {}).get("extra", []):
        ctx = dict(DEFAULT_EVENT, **{k: x[k] for k, _ in ROUTE_FIELDS if k in x})
        cases.append((x["note"], x.get("sid", intent["sids"][0]), ctx))
    return cases


def render_tests(intents, all_intents, alert_level):
    rules, files = ladder(), {}
    for intent in (i for i in intents if i["action"] in SIEM_ACTIONS):
        fired, lines, expect = set(), [], []
        cases = test_cases(intent)
        for k, (note, sid, ctx) in enumerate(cases, 1):
            rid, level, alert = expected(all_intents, rules, sid, ctx, intent["metadata"], fired, alert_level)
            lines.append(json.dumps(event(intent, sid, ctx)))
            expect.append(f"{k} {rid} {level} {'yes' if alert else 'no'}  # {note}")
        stem = f"intent-{intent['id']}"
        files[f"{stem}.txt"] = f"# {HEADER}\n" + "\n".join(lines) + "\n"
        files[f"{stem}.expect"] = f"# {HEADER}\n" + "\n".join(expect) + "\n"
    return files


# ---------- driver ----------

def outputs(intents, alert_level):
    files = {WAZUH_OUT: render_wazuh4(intents)}
    files.update({SURICATA_OUT / name: text for name, text in render_suricata(intents).items()})
    files.update({TESTS_OUT / name: text for name, text in render_tests(intents, intents, alert_level).items()})
    files.update({WAZUH5_OUT / name: text for name, text in render_wazuh5(intents, alert_level).items()})
    return files


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = p.parse_args(argv)
    alert_level = int(kitconfig.load()["WAZUH_ALERT_LEVEL"])
    try:
        intents = load_intents(alert_level=alert_level)
        files = outputs(intents, alert_level)
    except IntentError as e:
        print(f"render: {e}", file=sys.stderr)
        return 1
    stale_tests = {p for p in list(TESTS_OUT.glob("intent-*")) + list((WAZUH5_OUT / "rules").glob("*.yml"))
                   if p not in files}
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text] + sorted(stale_tests)
    if args.check:
        for path in stale:
            print(f"STALE {path.relative_to(ROOT)}")
        print(f"render --check: {len(intents)} intents, {len(files)} files, {len(stale)} stale")
        return 1 if stale else 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    for path in stale_tests:
        path.unlink()
    print(f"render: {len(intents)} intents -> {len(files)} files ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
