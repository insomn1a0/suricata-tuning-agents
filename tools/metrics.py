"""Metrics for the README and the CI job summary - computed, never typed by hand.

Tuning effect: the synthetic demo week (examples/lab/make_sample_eve.py) through the rule model of
tools/render.py - the ladder picks the parent from each alert's metadata, the generated tuning rules apply in
engine order, `ignore` windows use the event timestamps. The model is what the generated logtest cases verify
on the real engine; a raw logtest replay cannot be used here, because it processes a week of events in seconds
and every `ignore` window would cover the whole week.
Corpus: attack cases in tests/corpus/*/siem.yaml; with --corpus-result (JSON from corpus_test.py --json) the
engine-verified visibility is reported too.

Usage: metrics.py                 print the markdown block
       metrics.py --write         replace the block between the markers in README.md
       metrics.py --check         exit 1 if README.md's block is stale
       metrics.py --summary [--corpus-result FILE]   append the block to $GITHUB_STEP_SUMMARY"""
import argparse
import collections
import contextlib
import datetime
import io
import json
import os
import pathlib
import sys
import tempfile

import yaml

import kitconfig
import render

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START, END = "<!-- metrics:start (generated by tools/metrics.py - do not edit) -->", "<!-- metrics:end -->"


def demo_events():
    sys.path.insert(0, str(ROOT / "examples" / "lab"))
    import make_sample_eve  # noqa: E402 - deterministic generator
    with tempfile.TemporaryDirectory() as d, contextlib.redirect_stdout(io.StringIO()):
        make_sample_eve.main(d)
        lines = (pathlib.Path(d) / "week1" / "eve.json").read_text().splitlines()
    return [json.loads(line) for line in lines if line.strip()]


def ctx_of(event):
    return {"src": event["src_ip"], "dst": event["dest_ip"], "src_port": event.get("src_port"),
            "dst_port": event.get("dest_port"), "proto": event.get("proto")}


def ts(event):
    return datetime.datetime.strptime(event["timestamp"], "%Y-%m-%dT%H:%M:%S.%f%z")


def classify(events, intents, alert_level):
    """Per event: (visible before tuning, visible after, rule after)."""
    rules, rows, last = render.ladder(), render.wazuh_rules(intents), {}
    out = []
    for e in sorted(events, key=ts):
        meta = {k: v[0] for k, v in e["alert"].get("metadata", {}).items() if isinstance(v, list) and v}
        parent = render.ladder_select(rules, meta)
        before = rules[parent]["level"] >= alert_level
        sid, ctx = e["alert"]["signature_id"], ctx_of(e)
        hits = [(i, rid, n) for n, (i, route, rid) in enumerate(rows)
                if str(i["wazuh"]["parent"]) == parent and sid in i["sids"] and render.route_matches(route, ctx)]
        if not hits:
            out.append((e, before, before, parent))
            continue
        intent, rid, _ = min(hits, key=lambda h: render.engine_key(h[0]["level"], h[2]))
        visible = intent["level"] >= alert_level
        if visible and "rate_limit" in intent:
            window = datetime.timedelta(seconds=intent["rate_limit"]["ignore_seconds"])
            visible = rid not in last or ts(e) - last[rid] >= window
            if visible:
                last[rid] = ts(e)
        out.append((e, before, visible, str(rid)))
    return out


def corpus_cases():
    attacks = []
    for siem in sorted((ROOT / "tests" / "corpus").glob("*/siem.yaml")):
        attacks += [(siem.parent.name, exp["name"], exp["attack"]) for exp in yaml.safe_load(siem.read_text())["expect"]
                    if exp.get("attack")]
    return attacks


def block(corpus_result=None):
    cfg = kitconfig.load()
    alert_level = int(cfg["WAZUH_ALERT_LEVEL"])
    intents = render.load_intents()
    rows = classify(demo_events(), intents, alert_level)
    days = 7
    per_sid = collections.defaultdict(lambda: [0, 0, 0, ""])
    for e, before, after, _ in rows:
        s = per_sid[e["alert"]["signature_id"]]
        s[0] += 1
        s[1] += before
        s[2] += after
        s[3] = e["alert"]["signature"]
    total = [sum(v[i] for v in per_sid.values()) for i in range(3)]
    lines = [START, "", f"Demo week, analyst-visible level >= {alert_level} "
             f"({len(intents)} intents; rule model verified by the generated logtest cases):", "",
             "| SID | Signature | Alerts/day | Visible/day before | Visible/day after |", "|---|---|---|---|---|"]
    for sid, (n, b, a, sig) in sorted(per_sid.items(), key=lambda kv: -kv[1][1]):
        lines.append(f"| {sid} | {sig} | {n / days:.1f} | {b / days:.1f} | {a / days:.1f} |")
    change = (total[2] - total[1]) / total[1] * 100 if total[1] else 0
    lines += [f"| **all** | | **{total[0] / days:.1f}** | **{total[1] / days:.1f}** | **{total[2] / days:.1f}** "
              f"({change:+.0f}%) |", ""]
    lateral = [(b, a) for e, b, a, _ in rows if e["src_ip"] == "10.10.100.77" and e["dest_ip"] == "10.10.30.40"]
    lines.append(f"Lateral tool transfer in the demo data (exe to a workstation admin share): "
                 f"{sum(a for _, a in lateral)}/{len(lateral)} events still visible after tuning.")
    attacks = corpus_cases()
    if corpus_result:
        r = json.loads(pathlib.Path(corpus_result).read_text())
        lines.append(f"Regression corpus on the engines (Suricata {r.get('suricata', '?')}, {r.get('wazuh', '?')}): "
                     f"attacks visible **{r['attack_ok']}/{r['attack_total']}**, noise hidden "
                     f"{r['noise_ok']}/{r['noise_total']}; mutants killed are reported by `make test-e2e-mutant`.")
    else:
        lines.append(f"Regression corpus: {len(attacks)} attack cases ("
                     + ", ".join(sorted({a[2] for a in attacks})) + "); CI job `no-attack-lost` requires every one "
                     "visible after tuning on Suricata + Wazuh, and every mutant intent to break that.")
    lines += ["", END]
    return "\n".join(lines)


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--write", action="store_true")
    p.add_argument("--check", action="store_true")
    p.add_argument("--summary", action="store_true")
    p.add_argument("--corpus-result")
    args = p.parse_args(argv)
    text = block(args.corpus_result if args.summary else None)
    if args.summary:
        with open(os.environ.get("GITHUB_STEP_SUMMARY", "/dev/stdout"), "a") as f:
            f.write(text.replace(START, "## Tuning metrics").replace(END, "") + "\n")
        return 0
    if not (args.write or args.check):
        print(text)
        return 0
    readme = README.read_text()
    if START not in readme or END not in readme:
        print("metrics: markers missing in README.md", file=sys.stderr)
        return 1
    head, rest = readme.split(START, 1)
    new = head + text + rest.split(END, 1)[1]
    if args.check:
        stale = new != readme
        print(f"metrics --check: README block {'STALE - run make metrics' if stale else 'current'}")
        return 1 if stale else 0
    README.write_text(new)
    print("metrics: README block updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
