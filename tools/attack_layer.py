"""ATT&CK Navigator layer generated from the repo - what the kit detects and what it proves stays visible.

Score 3: a deployed local signature (suricata/rules/) AND a corpus case proving it stays visible after tuning.
Score 2: corpus proof through a corpus-only stand-in - detection depends on the user's ruleset.
Score 1: a deployed local signature without a corpus case.
Sources: `mitre_technique_id` in rule metadata, `attack:` in tests/corpus/*/siem.yaml.
Usage: attack_layer.py [--check]      writes docs/attack-layer.json (open it in ATT&CK Navigator)"""
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "attack-layer.json"


def techniques_in_rules(path):
    out = {}
    for f in sorted(pathlib.Path(path).glob("*.rules")) if pathlib.Path(path).is_dir() else [pathlib.Path(path)]:
        for line in f.read_text().splitlines():
            sid, msg = re.search(r"\bsid:\s*(\d+)\s*;", line), re.search(r'\bmsg:\s*"([^"]*)"', line)
            if not sid or line.lstrip().startswith("#"):
                continue
            for tid in re.findall(r"mitre_technique_id\s+(T\d{4}(?:\.\d{3})?)", line):
                out.setdefault(tid, []).append(f"{sid.group(1)} {msg.group(1) if msg else ''}".strip())
    return out


def corpus_attacks():
    out = {}
    for siem in sorted((ROOT / "tests" / "corpus").glob("*/siem.yaml")):
        for exp in yaml.safe_load(siem.read_text())["expect"]:
            if exp.get("attack"):
                out.setdefault(exp["attack"], []).append(f"{siem.parent.name}: {exp['name']}")
    return out


def layer():
    deployed = techniques_in_rules(ROOT / "suricata" / "rules")
    proven = corpus_attacks()
    techniques = []
    for tid in sorted(set(deployed) | set(proven)):
        score = 3 if tid in deployed and tid in proven else 2 if tid in proven else 1
        notes = [f"signature {s}" for s in deployed.get(tid, [])] + [f"corpus {c}" for c in proven.get(tid, [])]
        if score == 2:
            notes.append("detection in the corpus by a lab stand-in - depends on your ruleset")
        techniques.append({"techniqueID": tid, "score": score, "comment": "; ".join(notes), "enabled": True})
    return {
        "name": "suricata-tuning-agents coverage",
        "versions": {"layer": "4.5"},
        "domain": "enterprise-attack",
        "description": "Generated by tools/attack_layer.py. 3 = local signature + proven visible after tuning "
                       "(regression corpus); 2 = proven via a corpus stand-in; 1 = local signature only.",
        "techniques": techniques,
        "gradient": {"colors": ["#e8f1fb", "#3b82c4"], "minValue": 0, "maxValue": 3},
        "legendItems": [{"label": "signature + proven visible", "color": "#3b82c4"},
                        {"label": "proven visible via stand-in", "color": "#86b5df"},
                        {"label": "signature only", "color": "#c6dcf1"}],
    }


def main(argv):
    text = json.dumps(layer(), indent=2) + "\n"
    if "--check" in argv:
        stale = not OUT.exists() or OUT.read_text() != text
        print(f"attack-layer --check: {'STALE - run make attack-layer' if stale else 'current'}")
        return 1 if stale else 0
    OUT.write_text(text)
    print(f"attack-layer: {len(layer()['techniques'])} techniques -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
